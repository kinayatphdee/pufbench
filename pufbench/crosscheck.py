"""Cross-checks of paper Section IV-E.

Step 9a: the pypuf check (statistical). Our attackers run on instances
generated by pypuf, an independent simulator with its own weight convention
(all weights N(0, 1), bias weight zero) and its own noise implementation,
calibrated to the same output flip rate. The check passes for a cell if the
median N_A on pypuf instances lies inside our bootstrap 95% interval for the
same cell. pypuf's feed-forward PUF uses a different loop convention, so this
check covers the arbiter and k-XOR rows; the feed-forward row is covered by
the MATLAB check.

Commands:
  python -m pufbench.crosscheck pypuf-run --out results/C1_pypuf.csv \
         --families arbiter --seeds 0 1 2 3 4 --instances 0 1 2 3 4
  python -m pufbench.crosscheck pypuf-compare --ours results/A1.csv results/B1.csv \
         --pypuf results/C1_pypuf.csv
"""
from __future__ import annotations

import numpy as np

from .analysis import bootstrap_median, instance_budgets, load_results
from .runner import BUDGETS, ResultsFile, run_one


def run_pypuf(out, families=("arbiter", "xor3"), attackers=("lr",), noises=("delay", "uniform"),
              seeds=(0,), instances=(0, 1, 2, 3, 4), budgets=BUDGETS, log=print):
    """Run attackers on pypuf instances; results go to a separate file (never mixed with ours)."""
    from .pypuf_bridge import pypuf_cell_data
    res = ResultsFile(out)
    new = 0
    for fam in families:
        for s in seeds:
            for i in instances:
                todo = [(a, m, N) for a in attackers for m in noises for N in budgets
                        if not res.has(fam, a, m, s, i, N)]
                if not todo:
                    continue
                data = pypuf_cell_data(fam, s, i, p=0.05, n_train=max(100_000, max(budgets)))
                for a, m, N in todo:
                    row = run_one(data, a, m, N)
                    res.append(row)
                    new += 1
                    log(f"pypuf {fam} seed={s} inst={i} {a} {m:7s} N={N:6d}  "
                        f"fidelity={row['fidelity']:.4f}  ({row['seconds']:.1f} s)")
    return new


def compare_pypuf(ours_paths, pypuf_paths, thresholds=(0.95, 0.99)):
    """One row per (family, attacker, noise, A) present in the pypuf results."""
    ours, theirs = load_results(ours_paths), load_results(pypuf_paths)
    table = []
    for A in thresholds:
        ib_o, ib_p = instance_budgets(ours, A), instance_budgets(theirs, A)
        for cell, pv in sorted(ib_p.items()):
            if cell not in ib_o:
                continue
            med_o, lo, hi = bootstrap_median(list(ib_o[cell].values()))
            med_p = float(np.median(list(pv.values())))
            both_never = np.isinf(med_p) and np.isinf(med_o)
            table.append({"family": cell[0], "attacker": cell[1], "noise": cell[2], "A": A,
                          "ours_median": med_o, "ours_low": lo, "ours_high": hi,
                          "ours_n": len(ib_o[cell]), "pypuf_median": med_p, "pypuf_n": len(pv),
                          "pass": bool(both_never or lo <= med_p <= hi)})
    return table


def _fmt(x):
    return "never" if np.isinf(x) else f"{x:,.0f}"


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Cross-checks of Section IV-E.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("pypuf-run")
    r.add_argument("--out", required=True)
    r.add_argument("--families", nargs="+", default=["arbiter", "xor3"])
    r.add_argument("--attackers", nargs="+", default=["lr"])
    r.add_argument("--noises", nargs="+", default=["delay", "uniform"])
    r.add_argument("--seeds", nargs="+", type=int, default=[0])
    r.add_argument("--instances", nargs="+", type=int, default=[0, 1, 2, 3, 4])
    r.add_argument("--budgets", nargs="+", type=int, default=BUDGETS)
    c = sub.add_parser("pypuf-compare")
    c.add_argument("--ours", nargs="+", required=True)
    c.add_argument("--pypuf", nargs="+", required=True)
    a = ap.parse_args(argv)
    if a.cmd == "pypuf-run":
        n = run_pypuf(a.out, a.families, a.attackers, a.noises, a.seeds, a.instances, a.budgets)
        print(f"done: {n} new runs written to {a.out}")
    else:
        rows = compare_pypuf(a.ours, a.pypuf)
        print(f"{'family':8s} {'att':4s} {'noise':8s} {'A':>5s} {'ours: median (95% interval) [n]':>40s} "
              f"{'pypuf: median [n]':>20s}  result")
        for t in rows:
            o = f"{_fmt(t['ours_median'])} ({_fmt(t['ours_low'])}-{_fmt(t['ours_high'])}) [{t['ours_n']}]"
            p = f"{_fmt(t['pypuf_median'])} [{t['pypuf_n']}]"
            print(f"{t['family']:8s} {t['attacker']:4s} {t['noise']:8s} {t['A']:5.2f} {o:>40s} {p:>20s}  "
                  f"{'PASS' if t['pass'] else 'FAIL'}")
        print(f"\n{sum(t['pass'] for t in rows)} of {len(rows)} cells pass")


if __name__ == "__main__":
    main()